import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = resolve(repositoryRoot, "handoff/static-html");
const baseUrl = new URL(process.env.BASE_URL ?? "http://127.0.0.1:3000");
const publicOrigin = new URL(
  process.env.PUBLIC_ORIGIN ??
    "https://figwork-campus-partners.david-lin1521.chatgpt.site",
);

const pages = [
  { path: "/", file: "ambassador-page.html" },
  { path: "/terms", file: "terms-and-conditions.html" },
];

function absolutizeUrl(value) {
  if (
    !value ||
    value.startsWith("#") ||
    value.startsWith("data:") ||
    value.startsWith("mailto:") ||
    value.startsWith("tel:") ||
    value.startsWith("javascript:")
  ) {
    return value;
  }

  const resolved = new URL(value, baseUrl);
  if (resolved.origin === baseUrl.origin) {
    return new URL(`${resolved.pathname}${resolved.search}${resolved.hash}`, publicOrigin)
      .href;
  }
  return resolved.href;
}

async function fetchRequired(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Could not fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response;
}

async function inlineStyles(html, pageUrl) {
  const stylesheetPattern = /<link\b(?=[^>]*\brel=["']stylesheet["'])(?=[^>]*\bhref=["']([^"']+)["'])[^>]*>/gi;
  const matches = [...html.matchAll(stylesheetPattern)];

  for (const match of matches) {
    const stylesheetUrl = new URL(match[1], pageUrl);
    const stylesheet = await (await fetchRequired(stylesheetUrl)).text();
    html = html.replace(
      match[0],
      `<style data-static-exported>\n${stylesheet}\n</style>`,
    );
  }

  return html;
}

async function inlineImages(html, pageUrl) {
  const imagePattern = /<img\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi;
  const matches = [...html.matchAll(imagePattern)];

  for (const match of matches) {
    const source = match[1];
    if (source.startsWith("data:")) continue;

    const imageUrl = new URL(source, pageUrl);
    if (imageUrl.origin !== baseUrl.origin) continue;

    const response = await fetchRequired(imageUrl);
    const contentType = response.headers.get("content-type") ?? "application/octet-stream";
    const data = Buffer.from(await response.arrayBuffer()).toString("base64");
    const inlineSource = `data:${contentType};base64,${data}`;
    html = html.replace(match[0], match[0].replace(source, inlineSource));
  }

  return html;
}

function removeRuntime(html) {
  return html
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/<link\b(?=[^>]*\brel=["'](?:modulepreload|preload)["'])[^>]*>/gi, "")
    .replace(/<!--\$-->|<!--\/\$-->|<!--\$\?-->|<!--\$!-->|<!--F!-->/g, "");
}

function rewriteLocalUrls(html) {
  return html
    .replace(/\b(href|src|action)=(['"])([^'"]+)\2/gi, (full, attribute, quote, value) => {
      return `${attribute}=${quote}${absolutizeUrl(value)}${quote}`;
    })
    .replaceAll(baseUrl.origin, publicOrigin.origin);
}

function addStaticExportStyles(html) {
  const styles = `
<style data-static-export-overrides>
  html { scroll-behavior: smooth; }
  .reveal, .reveal.is-visible { opacity: 1 !important; transform: none !important; }
  @media (prefers-reduced-motion: reduce) { html { scroll-behavior: auto; } }
</style>`;
  return html.replace("</head>", `${styles}\n</head>`);
}

async function exportPage({ path, file }) {
  const pageUrl = new URL(path, baseUrl);
  let html = await (await fetchRequired(pageUrl)).text();

  html = await inlineStyles(html, pageUrl);
  html = await inlineImages(html, pageUrl);
  html = removeRuntime(html);
  html = rewriteLocalUrls(html);
  html = addStaticExportStyles(html);
  html = `<!-- Generated by npm run export:html. Edit the React source, then regenerate this file. -->\n${html}`;

  const destination = resolve(outputDirectory, file);
  await writeFile(destination, html, "utf8");
  console.log(`Exported ${path} -> ${destination}`);
}

await mkdir(outputDirectory, { recursive: true });

for (const page of pages) {
  await exportPage(page);
}
